-- V43 — 창 사용분 보고에 클라 측정 시각(measured_at) 저장 (GROMO-1407 · N34)
-- ════════════════════════════════════════════════════════════════════
-- · 종전 "마지막 도착 승리" upsert 는 정산 결과가 네트워크 도착 순서에 좌우됐다 — 포그라운드 sync 와
--   사일런트 푸시 트리거 sync 가 경합하거나, 타임아웃으로 앱은 실패 처리한 요청이 서버에 지연 도착하면
--   낮은 옛 값이 최신값을 덮는다(돈 경로). 이제 upsert 가 저장된 measured_at 보다 오래된 보고를
--   조용히 무시한다(역전 방어 — 비교는 리포지토리 ON CONFLICT ... WHERE 절).
-- · 미래 measured_at(서버 시각 +2분 초과)은 API 가 INVALID_MEASURED_AT 400 으로 거절한다 — 기기
--   시계가 앞서 있으면 이후의 정상 보고가 전부 "오래된 값"으로 버려져 낮은 사용분이 굳기 때문이다.
-- · 기존 행은 null — "시각 모름"으로 어떤 보고든 갱신을 허용한다(레거시 수용, 단조 강제는 값이
--   생긴 뒤부터).

ALTER TABLE public.group_challenge_members
    ADD COLUMN measured_at timestamp with time zone;
