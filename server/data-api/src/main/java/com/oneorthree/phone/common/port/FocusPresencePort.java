package com.oneorthree.phone.common.port;

import java.time.Instant;
import java.util.UUID;

/**
 * 「이 사람이 지금 집중 중이다」를 <b>다른 서비스가 볼 수 있는 곳</b>에 내놓는 포트 (GROMO-292).
 *
 * <p><b>왜 필요한가.</b> 채팅 서버는 집중 중인 사람의 접속을 막아야 하는데, 집중 세션의 정본은 이쪽
 * DB 에 있고 채팅은 그 DB 를 만지지 않는다(단방향 규칙). 매 발신마다 서버 간 HTTP 로 물어보는 방법도
 * 있지만 그러면 메시지 1건이 왕복 1회가 된다 — 그래서 <b>공유 Redis 에 리스를 놓아</b> 채팅이 O(1)
 * 조회로 판정하게 한다. 목표 아키텍처 A19 의 {@code presence:*} 네임스페이스가 이것이고,
 * <b>쓰기 주인은 이 서비스뿐</b>이다.
 *
 * <p><b>이 포트의 실패는 집중을 막지 않는다.</b> 구현은 전부 best-effort 여야 한다 — Redis 가 흔들린다고
 * 집중 시작이 실패하면, 부가 기능의 장애가 핵심 기능을 죽이는 셈이 된다. 대가는 「집중 중인데 채팅이
 * 열리는」 드문 창이고, 그 규칙은 스스로를 위한 규칙이라 그 방향의 실패를 수용한다.
 *
 * <p><b>반영 시점은 커밋 이후여야 한다.</b> 트랜잭션 안에서 리스를 놓으면 그 트랜잭션이 롤백됐을 때
 * 세션은 없는데 리스만 남아, 그 사람이 TTL 이 끝날 때까지 채팅에 못 들어간다. 이 규율은 구현이 지킨다
 * ({@code RedisFocusPresence}).
 *
 * <h2>왜 두 메서드 모두 sessionId 를 받는가</h2>
 * 커밋 이후 콜백은 <b>트랜잭션마다 다른 스레드에서</b> 돌기 때문에, 서로 다른 요청의 Redis 연산이
 * DB 커밋 순서와 어긋난 순서로 도착할 수 있다. 뽀모도로 회전처럼 「직전 세션 종료 + 새 세션 시작」이
 * 겹치는 순간이 그렇다. 값이 없는 단순 SET/DEL 이면:
 * <ul>
 *   <li>종료의 DEL 이 새 시작의 SET <b>뒤에</b> 도착 → 진행 중인 집중의 리스가 사라진다(채팅이 열린다)</li>
 *   <li>시작의 SET 이 종료의 DEL <b>뒤에</b> 도착 → <b>이미 끝난 집중의 리스가 되살아나 최대 13시간
 *       채팅이 막힌다</b></li>
 * </ul>
 * 그래서 <b>세션 id 를 값으로 싣고 조건부로만 쓴다</b> — 쓰기는 「더 새로운 세션일 때만」, 해제는
 * 「내가 놓은 그 세션일 때만」. 세션 id 가 UUID v7(시간 정렬)이라 「더 새로움」을 값 비교로 판정할 수 있다.
 *
 * <p>읽는 쪽(채팅)은 여전히 <b>존재 여부만</b> 본다 — 값의 의미는 쓰는 쪽만 안다.
 *
 * <h2>리스는 «언제나» {@code startedAt + 리스 수명} 에 만료한다</h2>
 * 그래서 두 쓰기 메서드가 모두 {@code startedAt} 을 받는다. 「놓는 시점부터 N시간」으로 잡으면
 * <b>늦게 놓을수록 백스톱이 뒤로 밀린다</b> — 11시간 59분 된 집중을 재구축이 그때 처음 놓으면 만료가
 * 시작 기준 25시간이 되어, 고아 스윕이 멈춘 동안 <b>이미 끝난 집중이 하루 넘게 채팅을 막는다.</b>
 * 백스톱의 정의는 「그 집중이 시작한 지 N시간」이지 「리스를 놓은 지 N시간」이 아니다.
 */
public interface FocusPresencePort {

    /**
     * 집중이 시작됐다 — 리스를 놓는다.
     *
     * @param startedAt 그 마커가 «시작한» 시각. 리스의 만료 기준이다 — 아래 참조
     * @param sessionId 이 시작이 가리키는 <b>진행 중 마커</b>의 id. 새로 만든 마커이거나(정상 경로),
     *                  이미 열려 있어 새로 만들지 않은 마커의 id다(순서 역전 방어 경로). 이 값보다
     *                  <b>오래된</b> 세션의 쓰기는 무시되므로, 늦게 도착한 옛 시작이 새 집중을 덮지 않는다
     */
    void focusStarted(UUID userId, UUID sessionId, Instant startedAt);

    /**
     * <b>재구축</b> — 정본에 진행 중인 집중이 있는데 리스가 «없을 때만» 놓는다.
     *
     * <p>{@link #focusStarted} 와 나눈 이유는 두 가지다.
     *
     * <p>첫째, <b>있는 리스를 건드리면 안 된다.</b> 재구축은 주기적으로 돈다 — 매번 TTL 을 지금부터
     * 다시 13시간으로 밀면, 고아 스윕이 멈춘 동안 「이미 끝난 집중이 채팅을 막는」 창이 13시간에서
     * 25시간으로 늘어난다. 채우기만 하고 손대지 않으면 그 창은 원래대로다.
     *
     * <p>둘째, <b>커밋을 기다릴 이유가 없다.</b> 이건 이미 커밋된 정본을 읽어서 미러를 맞추는
     * 작업이라, 되돌려질 트랜잭션이 없다.
     *
     * <p>실패는 여기서도 삼킨다 — 재구축은 <b>주기적으로</b> 돌아서, 이번에 못 놓은 리스는 다음
     * 회차가 놓는다. 그게 「Redis 가 살아난 뒤에 누가 다시 시도하는가」에 대한 답이다.
     *
     * @param startedAt 그 마커가 시작한 시각. 리스는 «놓는 시점»이 아니라 <b>이 시각</b>을 기준으로
     *                  만료한다 — 그러지 않으면 백스톱이 늘어난다(아래 참조)
     * @param sessionId 정본에서 읽은 진행 중 마커의 id. 그 사이 세션이 끝났다면 그 종료가 남긴
     *                  표식에 걸려 쓰기가 거부된다 — 끝난 집중이 되살아나지 않는다
     */
    void restoreLeaseIfMissing(UUID userId, UUID sessionId, Instant startedAt);

    /**
     * 집중이 끝났다(정상 종료·취소·POST 폴백 선점·고아 스윕) — 리스를 지운다.
     *
     * <p>지금 리스를 쥐고 있는 세션이 <b>이 세션이거나 그보다 오래된 것일 때만</b> 지운다. 그 사이
     * 새 집중이 시작됐다면 그쪽 리스는 날리지 않는다. 「더 오래된 것」까지 지우는 이유는 회전 중
     * 쓰기가 한 번 실패해 남은 잔존 리스를 스스로 치우기 위해서다({@code RedisFocusPresence} 참조).
     *
     * <p>지우지 못해도 TTL 이 백스톱이다. 다만 그동안 그 사람은 채팅에 못 들어가므로, 이쪽 실패는
     * 시작 쪽 실패보다 사용자에게 아프다.
     *
     * @param sessionId 끝난 세션의 id. null 이면 아무것도 하지 않는다 — 어느 리스를 지워야 할지
     *                  알 수 없는데 무조건 지우면 남의(새) 집중을 푸는 셈이 된다
     */
    void focusEnded(UUID userId, UUID sessionId);
}
