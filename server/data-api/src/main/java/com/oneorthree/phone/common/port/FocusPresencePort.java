package com.oneorthree.phone.common.port;

import java.util.UUID;

/**
 * 「이 사람이 지금 집중 중이다」를 <b>다른 서비스가 볼 수 있는 곳</b>에 내놓는 포트 (GROMO-292).
 *
 * <p><b>왜 필요한가.</b> 채팅 서버는 집중 중인 사람의 접속을 막아야 하는데, 집중 세션의 정본은 이쪽
 * DB 에 있고 채팅은 그 DB 를 만지지 않는다(단방향 규칙). 매 발신마다 서버 간 HTTP 로 물어보는 방법도
 * 있지만 그러면 메시지 1건이 왕복 1회가 된다 — 그래서 <b>공유 Redis 에 리스를 놓아</b> 채팅이 O(1)
 * 조회로 판정하게 한다. 목표 아키텍처 A19 의 {@code presence:*} 네임스페이스가 이것이고,
 * <b>쓰기 주인은 이 서비스뿐</b>이다.
 *
 * <p><b>이 포트의 실패는 집중을 막지 않는다.</b> 구현은 전부 best-effort 여야 한다 — Redis 가 흔들린다고
 * 집중 시작이 실패하면, 부가 기능의 장애가 핵심 기능을 죽이는 셈이 된다. 대가는 「집중 중인데 채팅이
 * 열리는」 드문 창이고, 그 규칙은 스스로를 위한 규칙이라 그 방향의 실패를 수용한다.
 *
 * <p><b>반영 시점은 커밋 이후여야 한다.</b> 트랜잭션 안에서 리스를 놓으면 그 트랜잭션이 롤백됐을 때
 * 세션은 없는데 리스만 남아, 그 사람이 TTL 이 끝날 때까지 채팅에 못 들어간다. 이 규율은 구현이 지킨다
 * ({@code RedisFocusPresence}).
 */
public interface FocusPresencePort {

    /**
     * 집중이 시작됐다 — 리스를 놓는다.
     *
     * <p>여러 번 불려도 안전하다(같은 키를 다시 쓸 뿐). 뽀모도로 마커 회전처럼 시작이 연달아 오는
     * 경로에서 TTL 이 갱신되는 효과가 있고, 그건 의도한 동작이다.
     */
    void focusStarted(UUID userId);

    /**
     * 집중이 끝났다(정상 종료·취소) — 리스를 지운다.
     *
     * <p>지우지 못해도 TTL 이 백스톱이다. 다만 그동안 그 사람은 채팅에 못 들어가므로, 이쪽 실패는
     * 시작 쪽 실패보다 사용자에게 아프다.
     */
    void focusEnded(UUID userId);
}
