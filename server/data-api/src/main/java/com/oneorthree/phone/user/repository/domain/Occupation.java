package com.oneorthree.phone.user.repository.domain;

/**
 * 유저가 온보딩에서 고르는 직군(공부·시험 분야). 이 값이 추천 집중 태그 프리셋과 통계 코호트를 가른다.
 *
 * <p>여기 있는 건 <b>내부 식별자</b>일 뿐이고 화면에 보이는 한글 표시명은 occupations 마스터가 들고 있다 —
 * 표시명만 바꾸는 건 이 enum 을 건드리지 않는다. 반대로 상수를 지우면 그 값을 저장한 기존 유저 행이
 * 깨지므로, 폐기는 마스터의 소프트 딜리트로 한다.
 */
public enum Occupation {
    // 코드는 영문(내부 식별자), 표시명(한글)은 occupations.display_name 으로 관리 (GROMO-631)
    // 아래 각 상수의 설명은 V48 이 시드하는 occupation_default_tags 의 기본 태그를 근거로 한다.
    /** 노무사 — 노동법·인사노무관리·행정쟁송법·사회보험법. */
    LABOR_ATTORNEY,
    /** 변리사 — 특허법·상표법·민사소송법·자연과학개론. */
    PATENT_ATTORNEY,
    /** 세무사 — 세법학·회계학·재정학·상법. */
    TAX_ACCOUNTANT,
    /** 공인회계사 — 재무회계·원가관리회계·세법·재무관리·경영학. */
    CPA,
    /** 감정평가사 — 감정평가이론·실무·민법·부동산학원론. */
    APPRAISER,
    /** 공무원 시험 — 국어·영어·한국사·행정법·행정학. */
    CIVIL_SERVANT,
    /** 경찰·소방 — 형법·형사소송법·경찰학에 체력 준비가 함께 붙는 유일한 직군. */
    POLICE_FIRE,
    /** 행정고시 — 행정법·행정학·경제학·정치학에 답안 작성·스터디 준비. */
    ADMIN_EXAM,
    /** 자격증 일반 — 특정 과목이 없어 이론 정리·기출·실기 같은 학습 단계로 태그를 준다. */
    CERTIFICATION,
    /** 중학생 — 국어·수학·영어·과학·사회·수행평가. */
    MIDDLE_SCHOOL,
    /** 고등학생(내신) — 국·수·영·탐구에 내신 대비·수행평가. 수능 준비는 {@link #CSAT}. */
    HIGH_SCHOOL,
    /** 수능 — 국·수·영·탐구에 모의고사·오답 정리. 내신 중심은 {@link #HIGH_SCHOOL}. */
    CSAT,
    /** 대학생 — 전공·과제·팀플·논문 읽기 등 학기 단위 학습. */
    UNIVERSITY,
    /** 취업 준비 — 자소서·직무 공부·포트폴리오·면접·인적성. */
    JOB_PREP,
    /** 어학 시험 — LC·RC·단어 암기·문법·스피킹. */
    ENGLISH_TEST,
    /** 개발 — 알고리즘·코딩테스트·CS·사이드 프로젝트. */
    CODING,
    /** 자기계발 — 독서·글쓰기·외국어·재테크처럼 시험이 목표가 아닌 학습. */
    SELF_DEVELOPMENT,
    /** 집중력 기르기 — 딥워크·명상·계획 세우기. 학습 주제가 아니라 습관이 목표다. */
    FOCUS_BUILDING,
    /** 그 외 — 위 어디에도 안 맞을 때. 태그도 공부·독서·작업처럼 일반명사다. */
    ETC
}
