package com.oneorthree.phone.group.repository.domain;

/**
 * 챌린지가 재는 지표 — <b>달성 방향이 서로 반대</b>라 목표 상한·판정·정산 그레이스가 전부 이 축으로 갈린다
 * (N51 · §A6-bis). 하루형 목표 상한은 FOCUS 1,080분(18h) · SCREEN_TIME 720분(12h)이고 V36 의 DB CHECK 가
 * 같은 값으로 최후 방어한다.
 */
public enum MissionCategory {
    /**
     * 집중 시간 — 목표 <b>이상</b>이면 달성(창형은 5분 관용치). 서버가 포커스 세션으로 직접 재므로
     * 값이 없으면 "0분 집중"이라는 사실이다(미계측이 아니다).
     */
    FOCUS,
    /**
     * 스크린타임 — 목표 <b>이하</b>여야 달성. 값의 출처가 기기 보고라 값이 없으면 "0분 사용"이 아니라
     * <b>미계측</b>(판정 불가)이고, 측정 권한에 동의한 유저만 진행분이 잡힌다(N50 · FR-21).
     * 측정 눈금 때문에 창형 목표는 15분 배수만 허용한다.
     */
    SCREEN_TIME
}
