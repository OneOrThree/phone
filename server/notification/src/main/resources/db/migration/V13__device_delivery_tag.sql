-- 기기 등록마다 새로 발급하는 수신 확인 태그(deliveryTag)를 기기 행에 둔다 (GROMO-2520).
--
-- 왜: 같은 FCM 토큰으로 계정·로그인 세션을 바꾸는 동안 이전 등록 앞으로 나가 FCM/APNs 에 대기 중이던 푸시가 새 등록
-- 뒤에도 도착한다. 등록 응답과 그 기기로 가는 모든 푸시 data 에 같은 태그를 실어, 앱이 자기가 저장한 태그와 다른
-- 푸시를 버리게 한다(docs/prd/fishcat/account/low-level-design.md 「후속 계약은 세 겹이다」 ②).
--
-- NULL 허용 · 기본값 · 백필 · 인덱스 없음: 이 배포 전에 만든 행은 앱에 태그를 준 적이 없다. 앱이 대조할 수 없는 값을
-- 지어 싣지 않는다 — 그 행으로 가는 푸시에는 키를 싣지 않고, 그 기기의 다음 등록이 값을 채운다. 발송 대상 조회는
-- user_id 로 하므로 인덱스도 필요 없다.
--
-- ownership_token 을 재사용하거나 그 해시로 파생하지 않는다. 소유권은 등록·삭제의 CAS 자격이라(V1 의 device_tokens
-- 머리말 ①) 푸시 payload 로 내보내면 그 값을 본 쪽이 CAS 를 통과한다. 태그는 별도 난수다.
ALTER TABLE device_tokens ADD COLUMN delivery_tag text;
