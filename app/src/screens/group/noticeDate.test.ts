// fmtNoticeDate 유닛 테스트 — 공지 카드 캡션의 경과일(§6-4).
//
// DST 회귀를 **KST에서** 재현한다. 러너 시간대는 Asia/Seoul로 고정돼 있고(jest.config.js),
// 샌드박스 안에서 process.env.TZ를 바꿔도 V8 시간대는 따라오지 않는다(확인함).
// 대신 한국이 실제로 서머타임을 쓰던 1988년(5/8~10/8)을 쓴다 — 그 전환일 자정과 다음 날 자정
// 사이는 23시간뿐이라, 로컬 자정끼리의 밀리초 차이를 86,400,000으로 나누던 옛 구현이 무너진다.
// 사용자가 실제로 만나는 상황은 미국·유럽 등 DST를 쓰는 기기의 봄 전환 직후로 동일한 결함이다.
import { fmtNoticeDate } from './noticeDate';

describe('경과일 표기', () => {
  test.each([
    ['같은 날', '2026-07-29T01:00:00+09:00', '2026-07-29T23:30:00+09:00', '오늘'],
    ['하루 전', '2026-07-28T23:00:00+09:00', '2026-07-29T00:30:00+09:00', '어제'],
    ['사흘 전', '2026-07-26T12:00:00+09:00', '2026-07-29T12:00:00+09:00', '3일 전'],
    ['일주일 전부터는 날짜', '2026-07-22T12:00:00+09:00', '2026-07-29T12:00:00+09:00', '7월 22일'],
  ])('%s', (_label, iso, now, expected) => {
    expect(fmtNoticeDate(iso, new Date(now))).toBe(expected);
  });

  test('파싱할 수 없는 값은 빈 문자열', () => {
    expect(fmtNoticeDate('어제쯤')).toBe('');
  });

  // 옛 구현: 23시간 / 24시간 → 내림 0 → 어제 공지가 '오늘'. 오차는 다음 날까지 밀려
  // 이틀 전 공지가 '어제'로 보인다. 달력 날짜 차이로 세면 하루 길이와 무관해진다.
  test('DST 전환 직후에도 어제·이틀 전 공지가 하루씩 당겨지지 않는다', () => {
    const now = new Date('1988-05-09T12:00:00+10:00'); // 전환 다음 날 정오(KDT)
    expect(fmtNoticeDate('1988-05-08T13:00:00+10:00', now)).toBe('어제'); // 전환일
    expect(fmtNoticeDate('1988-05-07T12:00:00+09:00', now)).toBe('2일 전'); // 전환 전날
    expect(fmtNoticeDate('1988-05-09T01:00:00+10:00', now)).toBe('오늘');
  });
});
