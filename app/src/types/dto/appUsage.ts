// 앱별 사용 시간 서버 보고 DTO — **아직 전송하지 않는다.**
//
// ⚠️ 이 파일은 다른 DTO들과 방향이 반대다. `screentime.ts` 등은 이미 있는 백엔드 DTO의
//    미러지만, **서버에는 이 계약이 아직 없다.** 여기가 앱이 먼저 제안하는 원본이고,
//    서버 구현이 붙을 때 이 모양을 그대로 쓰거나 바뀌면 여기와 백엔드를 함께 고친다.
//
// ## 🔴 배선 전에 반드시 선행돼야 하는 것
//
// 지금 앱 화면은 **「기기에서만 처리 · 서버 미전송」**이라고 고지한다 — 오늘 기준 사실이다.
// 이 DTO를 실제로 전송하는 순간 그 문구가 거짓이 되므로, 아래 셋이 **함께** 나가야 한다:
//
//   1. 개인정보 처리방침 갱신 — '앱별 사용 시간' 수집·이용 목적·보관 기간
//   2. 앱 내 동의 획득 — 스크린타임 권한 동의와 **별개**다(권한은 측정, 이건 전송)
//   3. Play 데이터 보안 폼 — '앱 활동' 수집으로 신고
//
// 하나라도 빠진 채 전송을 켜면 화면 고지·처리방침·스토어 신고가 서로 어긋난다.
// 그 상태는 단순 버그가 아니라 **허위 고지**다.
//
// 배선을 막는 가드가 있다 — `appUsage.guard.test.ts` 참고.

/** 하루치 보고에 담기는 앱 1건. */
export interface AppUsageEntryDto {
  /**
   * 집계 키. **표시 이름이 아니라 이것으로 묶는다** — 표시 이름은 기기 언어·제조사 스킨에
   * 따라 달라져서 같은 앱이 여러 줄로 갈린다.
   */
  packageName: string;
  /**
   * 그 기기에서 보이던 표시 이름. 사람이 읽을 수 있게 함께 보낸다 — 패키지명만 저장하면
   * 나중에 서버에서 무슨 앱인지 알 방법이 없다(우리 서버엔 패키지명↔이름 표가 없다).
   * 기기 로케일에 따라 같은 앱도 값이 다를 수 있으므로 **표시용으로만** 쓴다.
   */
  label: string;
  /** 그날 포그라운드 사용 시간(초, 0 이상). 분이 아닌 이유는 `AppUsage` 주석 참고. */
  seconds: number;
}

/** `POST /screen-time/app-usage` (예정) 요청 본문. */
export interface AppUsageReportRequest {
  /**
   * 대상 날짜 `YYYY-MM-DD` — **기기 로컬 기준**.
   *
   * `ScreenTimeRequest`는 `reportedAt`만 보내고 서버가 날짜를 추론하지만, 앱별 사용시간은
   * 하루 단위 집계가 곧 데이터의 정체라 날짜 축을 추론에 맡기면 안 된다. 자정 직후 보고나
   * 밀린 과거분 재전송에서 하루가 통째로 어긋난다.
   */
  date: string;
  /**
   * 위 `date`를 만든 기기의 IANA 시간대(예: `Asia/Seoul`).
   *
   * 로컬 날짜만 보내면 서버는 그 하루가 실제로 어느 구간인지 알 수 없다 — 시차가 다른
   * 사용자끼리 같은 `date`가 서로 다른 24시간을 가리킨다. 여행·이주로 시간대가 바뀐
   * 사용자의 데이터를 나중에 다시 해석하려면 이 값이 남아 있어야 한다.
   */
  timeZone: string;
  /**
   * 수집 플랫폼. 지금은 안드로이드뿐이다 — iOS는 DeviceActivityReport 익스텐션이 그린 뷰만
   * 임베드할 수 있고 **수치를 JS로 못 가져와서** 보낼 값 자체가 없다. 그래서 이 필드는
   * "안드로이드에서만 온다"는 사실을 데이터에 남긴다(iOS 사용자의 결측과 미수집을 구분).
   */
  platform: 'android';
  /**
   * 이 보고를 만든 **설치 단위 식별자**(`analytics.getDeviceId()`).
   *
   * 없으면 서버가 두 상황을 구분할 수 없다(코드리뷰 반영):
   *   - 같은 계정이 안드로이드 기기 **두 대**를 쓴 날 → 두 최종 보고의 `platform`·`date`·
   *     `timeZone` 이 전부 같다. 날짜로 upsert 하면 한 대의 사용량이 사라지고, 합산하면
   *     재시도 때 중복 집계된다.
   *   - **같은 보고의 재전송**(오프라인 후 재시도) → 합산하면 안 된다.
   *
   * 서버 저장 키와 멱등성 판정에 함께 쓰라는 뜻이다. `groupApi` 가 여러 기기 동시 사용을
   * 이미 명시적으로 다루고 있어 같은 축을 따른다.
   *
   * 저장 키는 `(userId, date, deviceId)` 이고 같은 키의 재전송은 **덮어쓴다**(합산이 아니다).
   * 그래야 오프라인 재시도가 중복으로 쌓이지 않는다. 다만 무조건 덮는 게 아니라 `reportedAt`
   * 순서와 `isFinal` 단조성을 지킨다 — 그쪽 주석 참고.
   *
   * ⚠️ 계정 식별자가 아니다 — 앱을 지웠다 깔면 바뀐다. 기기를 특정하는 값으로 쓰면 안 된다.
   */
  deviceId: string;
  /**
   * 이 설치가 **측정을 시작한 날**(`YYYY-MM-DD`, `screentimeMeasurementStartDate` 앵커).
   *
   * `deviceId` 는 설치 단위라 **재설치하면 바뀐다.** 그런데 안드로이드는 조회 시점에
   * UsageStats 를 다시 읽으므로, 재설치 후 같은 날짜를 새 ID 로 또 보고할 수 있다 —
   * 서버가 기기별로 합산하면 **재설치 전 보고와 중복 집계된다**(코드리뷰 반영).
   *
   * 서버는 이 값보다 **이전 날짜의 보고를 받지 않는다.** 그 날은 이 설치가 측정하지 않은
   * 구간이고, 이미 다른 설치가 보고했거나 아무도 보고하지 않은 것이지 이 설치가 채울 몫이
   * 아니다. 클라이언트도 같은 규칙으로 과거분을 만들지 않는다.
   *
   * ⚠️ **이 값은 하한이 아니다**(코드리뷰 12차) — `consentDate` 를 함께 봐야 한다. 아래 참고.
   */
  measurementStartDate: string;
  /**
   * 이 사용자가 **앱별 사용량의 서버 전송에 동의한 날**(`YYYY-MM-DD`).
   *
   * ⚠️ `measurementStartDate` 로 대신할 수 없다. 그 앵커는 스크린타임 **측정 모니터를
   *    등록할 때** 찍히는데(`screentimeSync.ts`), 그건 기기 안에서 총 사용시간을 재기
   *    시작한 시점이지 **앱별 기록을 밖으로 내보내도 좋다는 동의가 아니다.** 둘을 같은
   *    값으로 두면, 어제까지 기기 내 측정만 하던 사용자가 오늘 전송에 동의했을 때
   *    **동의 전날의 앱별 기록이 그대로 올라간다** — 측정 앵커보다 뒤라는 이유로 서버도
   *    받아들인다.
   *
   * **하한은 둘 중 늦은 쪽이다**: `date >= max(measurementStartDate, consentDate)`.
   * 앞은 "이 설치가 그날을 실제로 측정했는가", 뒤는 "그날 것을 보낼 권한이 있는가"로
   * 서로 다른 질문이라 둘 다 필요하다. 클라이언트가 그런 보고를 만들지 않고, 서버도
   * 같은 규칙으로 거부한다(신뢰 경계가 앱이 아니다).
   *
   * 동의를 철회했다 다시 하면 **새 동의일로 갱신한다** — 철회 기간의 기록은 보낼 권한이 없다.
   */
  consentDate: string;
  /**
   * 사용 많은 순. **사용 0인 앱은 담지 않는다** — 설치만 하고 안 쓴 앱 목록은 사용 기록이
   * 아니라 설치 앱 목록이고, 그건 우리가 받을 이유가 없는 별개의 개인정보다.
   */
  entries: AppUsageEntryDto[];
  /**
   * 보고 시각(Instant, ISO 문자열).
   *
   * **서버의 순서 판정 기준이다**(코드리뷰 12차). 저장 키가 같은 재전송을 그냥 덮어쓰면,
   * 중간 보고의 응답이 유실돼 재시도되는 사이 최종 보고가 먼저 도착한 경우 **늦게 도착한
   * 중간 요청이 확정 데이터를 더 낮은 스냅샷으로 덮는다.** 저장된 것보다 오래된
   * `reportedAt` 은 무시한다.
   */
  reportedAt: string;
  /**
   * 최종 보고(그날이 끝나 확정)면 true, 오늘 중간 동기화면 false.
   * `ScreenTimeRequest.isFinal`과 같은 규약 — 서버는 final만 확정 저장한다.
   *
   * **단조다** — 한 번 `true` 로 확정된 행은 중간 보고로 강등하지 않는다. `reportedAt`
   * 비교만으로는 부족하다: 기기 시계가 어긋나면 늦게 만든 중간 보고가 더 이른 시각을
   * 달고 올 수 있고, 그러면 순서 판정이 통과시켜 버린다.
   */
  isFinal: boolean;
}
